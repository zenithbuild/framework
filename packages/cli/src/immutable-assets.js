import { readFile, stat, writeFile } from 'node:fs/promises';
import { join, resolve, sep } from 'node:path';
import { stripBasePath } from './base-path.js';
import { IMMUTABLE_CACHE_CONTROL, REVALIDATE_CACHE_CONTROL } from './static-delivery.js';

export { IMMUTABLE_CACHE_CONTROL, REVALIDATE_CACHE_CONTROL };

const MAX_WALK = 2000;
const DEV_STABLE_ASSET = /\.dev\.(?:js|mjs|css)$/i;
const HASH_TOKEN = /(?:^|\.)[0-9a-f]{8}(?:\.|$)/;
const VENDOR_CHUNK_TOKEN = /[-.][A-Za-z0-9_]{8,}(?:\.|$)/;
const JS_SPECIFIER = /(?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s*)['"]([^'"\n]+)['"]/g;
const CSS_SPECIFIER = /@import\s+(?:url\(\s*)?['"]([^'"]+)['"]|url\(\s*['"]([^'"]+)['"]\s*\)/g;
const GENERATED_EXACT_HEADER = '# Generated by Zenith: content-hashed build assets';
const GENERATED_STATIC_HEADER = '# Generated by Zenith: static files that are not content-hashed';

function normalizeRequestPath(value) {
    if (typeof value !== 'string' || value.length === 0) {
        return null;
    }
    let path = value.split('?')[0].split('#')[0];
    try {
        path = decodeURI(path);
    } catch {
        return null;
    }
    if (!path.startsWith('/') || path.startsWith('//')) {
        return null;
    }
    path = path.replace(/\/{2,}/g, '/');
    if (path.length > 1) {
        path = path.replace(/\/+$/, '');
    }
    if (path.includes('\0') || path.split('/').includes('..')) {
        return null;
    }
    return path;
}

/**
 * A path is content-hashed when it lives under /assets/ and its filename
 * carries a bundler content hash. Dev-stable names (*.dev.js) are excluded.
 * This check is applied only to manifest seeds and imports reached from them.
 *
 * @param {string} requestPath
 */
export function isContentHashedAssetPath(requestPath) {
    const pathname = normalizeRequestPath(requestPath);
    if (!pathname || !pathname.includes('/assets/')) {
        return false;
    }
    const name = pathname.slice(pathname.lastIndexOf('/') + 1);
    if (!name || DEV_STABLE_ASSET.test(name)) {
        return false;
    }
    if (HASH_TOKEN.test(name)) {
        return true;
    }
    if (pathname.includes('/assets/vendor-chunks/') || pathname.includes('/assets/vendor-assets/')) {
        return VENDOR_CHUNK_TOKEN.test(name);
    }
    return false;
}

function bundlerSeedPaths(bundlerManifest) {
    const chunks = bundlerManifest?.chunks && typeof bundlerManifest.chunks === 'object'
        ? Object.values(bundlerManifest.chunks)
        : [];
    return [
        bundlerManifest?.entry,
        bundlerManifest?.core,
        bundlerManifest?.router,
        bundlerManifest?.css,
        bundlerManifest?.vendor,
        ...chunks
    ].filter((value) => typeof value === 'string' && value.length > 0);
}

async function resolveStaticAsset(staticDir, basePath, requestPath) {
    const stripped = stripBasePath(requestPath, basePath);
    const relativeUrl = stripped === null ? requestPath : stripped;
    const relative = relativeUrl.replace(/^\/+/, '');
    if (!relative.startsWith('assets/') || relative.split('/').includes('..')) {
        return null;
    }
    const root = resolve(staticDir);
    const filePath = resolve(root, relative);
    if (filePath !== root && !filePath.startsWith(`${root}${sep}`)) {
        return null;
    }
    try {
        const info = await stat(filePath);
        return info.isFile() ? filePath : null;
    } catch {
        return null;
    }
}

function isLocalSpecifier(specifier) {
    if (!specifier || specifier.startsWith('data:') || specifier.startsWith('http:') || specifier.startsWith('https:') || specifier.startsWith('//')) {
        return false;
    }
    return specifier.startsWith('.') || specifier.startsWith('/');
}

function resolveSpecifier(fromPath, specifier) {
    const clean = String(specifier || '').split('?')[0].split('#')[0];
    if (!isLocalSpecifier(clean)) {
        return null;
    }
    if (clean.startsWith('/')) {
        return normalizeRequestPath(clean);
    }
    try {
        return normalizeRequestPath(new URL(clean, `http://local${fromPath}`).pathname);
    } catch {
        return null;
    }
}

function extractSpecifiers(source, extension) {
    const pattern = extension === '.css' ? CSS_SPECIFIER : JS_SPECIFIER;
    const specs = [];
    for (const match of source.matchAll(pattern)) {
        const spec = match[1] || match[2];
        if (typeof spec === 'string' && spec.length > 0) {
            specs.push(spec);
        }
    }
    return specs;
}

/**
 * Allowlist of request paths that are proven content-hashed.
 * Seeds are bundler manifest fields only. Helper modules, component assets,
 * and extra vendor files are included when a static import, @import, or
 * url() from a seed resolves to an existing content-hashed file under assets/.
 * Files the walk cannot see stay off the list.
 *
 * @param {{ staticDir: string, bundlerManifest: object, basePath?: string }} options
 * @returns {Promise<string[]>}
 */
export async function collectImmutableAssetPaths({ staticDir, bundlerManifest, basePath = '/' }) {
    const immutable = new Set();
    const seen = new Set();
    const queue = bundlerSeedPaths(bundlerManifest);
    let walked = 0;

    while (queue.length > 0 && walked < MAX_WALK) {
        const requestPath = normalizeRequestPath(queue.shift());
        if (!requestPath || seen.has(requestPath)) {
            continue;
        }
        seen.add(requestPath);
        walked += 1;
        if (!isContentHashedAssetPath(requestPath)) {
            continue;
        }
        const filePath = await resolveStaticAsset(staticDir, basePath, requestPath);
        if (!filePath) {
            continue;
        }
        immutable.add(requestPath);
        const extension = filePath.slice(filePath.lastIndexOf('.')).toLowerCase();
        if (extension !== '.js' && extension !== '.mjs' && extension !== '.css') {
            continue;
        }
        let source = '';
        try {
            source = await readFile(filePath, 'utf8');
        } catch {
            continue;
        }
        for (const specifier of extractSpecifiers(source, extension)) {
            const next = resolveSpecifier(requestPath, specifier);
            if (next && !seen.has(next)) {
                queue.push(next);
            }
        }
    }

    return [...immutable].sort();
}

export function expandImmutableRequestPaths(paths, basePath = '/') {
    const expanded = new Set();
    for (const value of Array.isArray(paths) ? paths : []) {
        const requestPath = normalizeRequestPath(value);
        if (!requestPath || !isContentHashedAssetPath(requestPath)) {
            continue;
        }
        expanded.add(requestPath);
        const stripped = stripBasePath(requestPath, basePath);
        if (stripped && stripped.startsWith('/assets/') && isContentHashedAssetPath(stripped)) {
            expanded.add(stripped);
        }
    }
    return [...expanded].sort();
}

function escapeRegex(value) {
    return String(value).replace(/[|\\{}()[\]^$+*?.-]/g, '\\$&');
}

export function createVercelImmutableAssetRoutes(manifest) {
    const paths = expandImmutableRequestPaths(manifest?.assets?.immutable, manifest?.base_path || '/');
    return paths.map((path) => ({
        src: `^${escapeRegex(path)}$`,
        headers: { 'Cache-Control': IMMUTABLE_CACHE_CONTROL },
        continue: true
    }));
}

function userExactPaths(source) {
    const paths = new Set();
    for (const line of String(source || '').split(/\r?\n/)) {
        if (!line || line.startsWith(' ') || line.startsWith('\t') || line.startsWith('#')) {
            continue;
        }
        const path = line.trim();
        if (path.startsWith('/') && !path.includes('*') && !path.includes(':')) {
            paths.add(path);
        }
    }
    return paths;
}

function stripGeneratedBlocks(source) {
    const lines = String(source || '').split(/\r?\n/);
    const kept = [];
    let skipping = false;
    for (const line of lines) {
        if (line === GENERATED_EXACT_HEADER || line === GENERATED_STATIC_HEADER) {
            skipping = true;
            continue;
        }
        if (skipping) {
            if (line.trim() === '') {
                skipping = false;
            }
            continue;
        }
        kept.push(line);
    }
    return kept.join('\n').replace(/^\n+/, '').replace(/\n+$/, '');
}

export function mergeNetlifyHeaders(existing, requestPaths) {
    const user = stripGeneratedBlocks(existing);
    const userHasCatchAll = user.split(/\r?\n/).some((line) => line.trim() === '/*');
    const claimed = userExactPaths(user);
    const generatedExact = expandImmutableRequestPaths(requestPaths, '/')
        .filter((path) => !claimed.has(path));
    const blocks = [];
    if (generatedExact.length > 0) {
        const lines = [GENERATED_EXACT_HEADER];
        for (const path of generatedExact) {
            lines.push(path, `  Cache-Control: ${IMMUTABLE_CACHE_CONTROL}`);
        }
        blocks.push(lines.join('\n'));
    }
    if (user) {
        blocks.push(user);
    }
    if (!userHasCatchAll) {
        blocks.push([
            GENERATED_STATIC_HEADER,
            '/*',
            `  Cache-Control: ${REVALIDATE_CACHE_CONTROL}`
        ].join('\n'));
    }
    return `${blocks.join('\n\n')}\n`;
}

export async function writeNetlifyCacheHeaders(publishDir, manifest) {
    const headerPath = join(publishDir, '_headers');
    let existing = '';
    try {
        existing = await readFile(headerPath, 'utf8');
    } catch (error) {
        if (error?.code !== 'ENOENT') {
            throw error;
        }
    }
    const paths = expandImmutableRequestPaths(manifest?.assets?.immutable, manifest?.base_path || '/');
    await writeFile(headerPath, mergeNetlifyHeaders(existing, paths), 'utf8');
}

export async function loadImmutableAssetSet({ projectRoot, distDir }) {
    const candidates = [];
    if (projectRoot) {
        candidates.push(join(projectRoot, '.zenith-output', 'manifest.json'));
    }
    if (distDir) {
        candidates.push(join(distDir, '..', '.zenith-output', 'manifest.json'));
    }
    for (const candidate of candidates) {
        try {
            const parsed = JSON.parse(await readFile(candidate, 'utf8'));
            if (!Array.isArray(parsed?.assets?.immutable)) {
                continue;
            }
            return new Set(parsed.assets.immutable.filter((entry) => typeof entry === 'string'));
        } catch (error) {
            if (error?.code !== 'ENOENT') {
                continue;
            }
        }
    }
    return new Set();
}
